def all_listed_tools() -> set[str]:
    return {t for cat in CATEGORIES for item in cat["items"] for t in item["tools"]}


def unlisted_tools(registered: list[str]) -> list[str]:
    listed = all_listed_tools()
    return sorted(name for name in registered if name not in listed)
